function originEnLabel(origin: string): string {
  const labels: Record<string, string> = {
    Arab: 'Arabic',
    Melayu: 'Malay',
    Parsi: 'Persian',
    Latin: 'Latin',
    Yunani: 'Greek',
    'Arab/Eropah': 'Arabic/European',
    'Parsi/Arab': 'Persian/Arabic',
    'Yunani/Arab': 'Greek/Arabic',
    'Arab/Melayu': 'Arabic/Malay',
    'Arab/Parsi': 'Arabic/Persian',
    'Arab/Ibrani': 'Arabic/Hebrew',
    'Melayu/Arab': 'Malay/Arabic',
    'Arab/Urdu': 'Arabic/Urdu',
    'Turki/Arab': 'Turkish/Arabic',
    'Arab/Yunani': 'Arabic/Greek',
    'Arab/Sanskrit': 'Arabic/Sanskrit',
  };
  return labels[origin] ?? origin;
}

const seen = new Set<string>();

export const NAMES: BabyName[] = RAW.filter(([name]) => {
  const key = name.toLowerCase();
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
}).map(([name, gender, meaning, meaningEn, origin, themes]) => ({
  name,
  slug: slugify(name),
  gender,
  meaning,
  meaningEn,
  origin,
  originEn: originEnLabel(origin),
  themes: themes.filter((t) => t !== 'keberanian'),
}));

export function getNameBySlug(slug: string): BabyName | undefined {
  return NAMES.find((n) => n.slug === slug);
}

export function getNamesByGender(gender: 'lelaki' | 'perempuan'): BabyName[] {
  return NAMES.filter((n) => n.gender === gender || n.gender === 'unisex').sort((a, b) =>
    a.name.localeCompare(b.name, 'ms'),
  );
}

export function getNamesByLetter(letter: string): BabyName[] {
  const L = letter.toLowerCase();
  return NAMES.filter((n) => n.name.toLowerCase().startsWith(L)).sort((a, b) =>
    a.name.localeCompare(b.name, 'ms'),
  );
}

export function getNamesByTheme(theme: string): BabyName[] {
  return NAMES.filter((n) => n.themes.includes(theme)).sort((a, b) =>
    a.name.localeCompare(b.name, 'ms'),
  );
}

export function getRelatedNames(name: BabyName, limit = 6): BabyName[] {
  const scored = NAMES.filter((n) => n.slug !== name.slug).map((n) => {
    let score = 0;
    if (n.gender === name.gender) score += 2;
    score += n.themes.filter((t) => name.themes.includes(t)).length * 3;
    if (n.name[0]?.toLowerCase() === name.name[0]?.toLowerCase()) score += 1;
    return { n, score };
  });
  return scored
    .sort((a, b) => b.score - a.score || a.n.name.localeCompare(b.n.name, 'ms'))
    .slice(0, limit)
    .map((x) => x.n);
}

export function getLettersWithNames(): string[] {
  const set = new Set(NAMES.map((n) => n.name[0]!.toUpperCase()));
  return [...set].sort();
}

export function genderLabel(gender: Gender): string {
  if (gender === 'lelaki') return 'Lelaki';
  if (gender === 'perempuan') return 'Perempuan';
  return 'Unisex';
}

export function genderLabelEn(gender: Gender): string {
  if (gender === 'lelaki') return 'Boy';
  if (gender === 'perempuan') return 'Girl';
  return 'Unisex';
}
